"""Analyze the CSV emitted by a research project's experiment runner."""

from __future__ import annotations

import csv
import io
import math
import statistics
from collections import defaultdict
from itertools import combinations
from typing import Any


REQUIRED_COLUMNS = {"experiment", "dataset", "system", "seed", "metric", "value", "status", "note"}
MAX_ROWS = 5_000
MAX_GROUPS = 2_000
MAX_COMPARISON_CELLS = 250
MAX_COMPARISONS = 2_000

# Two-sided 95% Student-t critical values for 1..29 degrees of freedom.
_T_975 = (
    0.0, 12.706, 4.303, 3.182, 2.776, 2.571, 2.447, 2.365, 2.306, 2.262,
    2.228, 2.201, 2.179, 2.160, 2.145, 2.131, 2.120, 2.110, 2.101, 2.093,
    2.086, 2.080, 2.074, 2.069, 2.064, 2.060, 2.056, 2.052, 2.048, 2.045,
)


def _t_critical(sample_size: int) -> float:
    degrees = sample_size - 1
    return _T_975[degrees] if degrees < len(_T_975) else 1.96


def analyze_results_csv(csv_text: str) -> dict[str, Any]:
    """Validate results.csv and summarize systems with paired seed comparisons.

    The returned comparison interval is a paired t interval over seed-level scores. It is
    descriptive; a small number of seeds does not establish statistical significance.
    """
    try:
        reader = csv.reader(io.StringIO(csv_text.lstrip("\ufeff"), newline=""))
        headers = next(reader, None)
    except csv.Error as exc:
        raise ValueError(f"Could not read the CSV header: {exc}") from exc
    if not headers:
        raise ValueError("The CSV is empty. Choose the results.csv generated by the project runner.")

    normalized_headers = [header.strip().lower() for header in headers]
    if len(set(normalized_headers)) != len(normalized_headers):
        raise ValueError("The CSV has duplicate column names.")
    missing = REQUIRED_COLUMNS - set(normalized_headers)
    if missing:
        raise ValueError(f"Missing required results.csv columns: {', '.join(sorted(missing))}.")

    parsed_rows: list[dict[str, str]] = []
    try:
        for line_number, fields in enumerate(reader, start=2):
            if not fields or all(not field.strip() for field in fields):
                continue
            if len(fields) != len(normalized_headers):
                raise ValueError(f"Row {line_number} has {len(fields)} cells; expected {len(normalized_headers)}.")
            parsed_rows.append(dict(zip(normalized_headers, (field.strip() for field in fields), strict=True)))
            if len(parsed_rows) > MAX_ROWS:
                raise ValueError(f"The CSV has more than {MAX_ROWS:,} rows. Analyze one experiment export at a time.")
    except csv.Error as exc:
        raise ValueError(f"Could not parse the CSV: {exc}") from exc

    if not parsed_rows:
        raise ValueError("The CSV contains a header but no result rows.")

    status_counts: dict[str, int] = defaultdict(int)
    issues: list[dict[str, str | int]] = []
    # group -> seed -> values; a repeated system/metric/seed is averaged before comparisons.
    grouped: dict[tuple[str, str, str, str], dict[str, list[float]]] = defaultdict(lambda: defaultdict(list))
    unseeded: dict[tuple[str, str, str, str], list[float]] = defaultdict(list)
    condition_systems: dict[tuple[str, str, str], set[str]] = defaultdict(set)
    valid_rows = 0

    for line_number, row in enumerate(parsed_rows, start=2):
        status = row["status"].lower() or "unknown"
        status_counts[status] += 1
        if status != "ok":
            if len(issues) < 20:
                issues.append({
                    "row": line_number,
                    "status": status,
                    "system": row["system"] or "-",
                    "metric": row["metric"] or "-",
                    "note": row["note"][:500],
                })
            continue

        labels = (row["experiment"], row["dataset"], row["system"], row["metric"])
        if any(not label or label == "-" for label in labels):
            raise ValueError(f"Row {line_number} is marked ok but is missing its experiment, dataset, system, or metric.")
        try:
            value = float(row["value"])
        except ValueError as exc:
            raise ValueError(f"Row {line_number} is marked ok but its value is not numeric.") from exc
        if not math.isfinite(value):
            raise ValueError(f"Row {line_number} has a non-finite metric value.")

        experiment, dataset, system, metric = labels
        key = (experiment, dataset, system, metric)
        seed = row["seed"]
        if seed and seed != "-":
            grouped[key][seed].append(value)
        else:
            unseeded[key].append(value)
        condition_systems[(experiment, dataset, metric)].add(system)
        valid_rows += 1

    if valid_rows == 0:
        raise ValueError("No rows have status 'ok' and a numeric value yet. Fix TODO/error rows and try again.")
    if len(grouped) + len(unseeded) > MAX_GROUPS:
        raise ValueError(f"The CSV creates more than {MAX_GROUPS:,} result groups. Analyze one experiment export at a time.")
    if any(len(systems) > 10 for systems in condition_systems.values()):
        raise ValueError("A metric group contains more than 10 systems; reduce the CSV to the systems you want to compare.")

    seed_values: dict[tuple[str, str, str, str], dict[str, float]] = {}
    summaries: list[dict[str, Any]] = []
    all_keys = set(grouped) | set(unseeded)
    for key in sorted(all_keys):
        per_seed = {seed: statistics.fmean(values) for seed, values in grouped[key].items()}
        seed_values[key] = per_seed
        values = [*per_seed.values(), *unseeded[key]]
        experiment, dataset, system, metric = key
        summaries.append({
            "experiment": experiment,
            "dataset": dataset,
            "system": system,
            "metric": metric,
            "seed_count": len(per_seed),
            "mean": round(statistics.fmean(values), 6),
            "std": round(statistics.stdev(values), 6) if len(values) > 1 else 0.0,
        })

    condition_keys = sorted({(exp, dataset, metric) for exp, dataset, _system, metric in all_keys})
    if len(condition_keys) > MAX_COMPARISON_CELLS:
        raise ValueError(
            f"The CSV contains more than {MAX_COMPARISON_CELLS} experiment/dataset/metric groups. "
            "Analyze a smaller export."
        )

    comparisons: list[dict[str, Any]] = []
    for condition in condition_keys:
        experiment, dataset, metric = condition
        systems = sorted(condition_systems[condition])
        for system_a, system_b in combinations(systems, 2):
            key_a = (experiment, dataset, system_a, metric)
            key_b = (experiment, dataset, system_b, metric)
            seeds_a, seeds_b = seed_values.get(key_a, {}), seed_values.get(key_b, {})
            shared_seeds = sorted(set(seeds_a) & set(seeds_b))
            if not shared_seeds:
                continue
            differences = [seeds_b[seed] - seeds_a[seed] for seed in shared_seeds]
            delta = statistics.fmean(differences)
            if len(differences) > 1:
                margin = _t_critical(len(differences)) * statistics.stdev(differences) / math.sqrt(len(differences))
                ci_lower, ci_upper = delta - margin, delta + margin
            else:
                ci_lower = ci_upper = None
            comparisons.append({
                "experiment": experiment,
                "dataset": dataset,
                "metric": metric,
                "system_a": system_a,
                "system_b": system_b,
                "paired_seed_count": len(shared_seeds),
                "mean_difference": round(delta, 6),
                "ci95_lower": round(ci_lower, 6) if ci_lower is not None else None,
                "ci95_upper": round(ci_upper, 6) if ci_upper is not None else None,
            })
            if len(comparisons) > MAX_COMPARISONS:
                raise ValueError(
                    f"The CSV creates more than {MAX_COMPARISONS:,} pairwise comparisons. "
                    "Analyze a smaller export."
                )

    return {
        "rows_seen": len(parsed_rows),
        "rows_analyzed": valid_rows,
        "status_counts": dict(sorted(status_counts.items())),
        "issues": issues,
        "summaries": summaries,
        "comparisons": comparisons,
        "notes": [
            "Δ is system B minus system A; whether a positive value is better depends on the metric.",
            "The interval is a paired 95% t interval over shared random seeds, not over individual examples.",
            "With fewer than five paired seeds, treat the interval as exploratory; it does not establish significance.",
            "Only the summary is saved to this project. The uploaded CSV is analyzed in memory and discarded.",
        ],
    }
